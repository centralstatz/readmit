#' Initialize persistent history for an RRP project
#'
#' Create `state/history.duckdb` and its empty `runs` and `assessments` tables
#' for an existing project. This is separate from project creation and does not
#' execute assessments or generate analytical products.
#'
#' @param path Path to an existing RRP project that passes structural validation.
#' @return The normalized project path, invisibly.
#' @details Initialization refuses to overwrite any existing `state/` directory.
#'   Project-authored scripts are loaded during structural validation, but their
#'   source-mapping and risk-provider functions are not called.
#' @examples
#' project <- tempfile("rrp-state-")
#' rrp_project_init(project, "example-rrp")
#' rrp_state_init(project)
#' unlink(project, recursive = TRUE)
#' @export
rrp_state_init <- function(path) {
  rrp_project_validate(path)
  root <- normalizePath(path, winslash = "/", mustWork = TRUE)
  state <- file.path(root, "state")
  if (file.exists(state)) {
    stop("Analytical state already exists; state/ was not changed.",
         call. = FALSE)
  }
  if (!dir.create(state)) {
    stop("Could not create the project's state/ directory.", call. = FALSE)
  }

  connection <- NULL
  complete <- FALSE
  tryCatch({
    connection <- DBI::dbConnect(duckdb::duckdb(),
                                 dbdir = file.path(state, "history.duckdb"))
    DBI::dbExecute(connection, paste(
      "CREATE TABLE runs (",
      "run_id VARCHAR PRIMARY KEY,",
      "project_id VARCHAR NOT NULL,",
      "as_of_time TIMESTAMPTZ NOT NULL,",
      "created_at TIMESTAMPTZ NOT NULL,",
      "source_mapping_script VARCHAR NOT NULL,",
      "risk_provider_script VARCHAR NOT NULL)"
    ))
    DBI::dbExecute(connection, paste(
      "CREATE TABLE assessments (",
      "run_id VARCHAR NOT NULL,",
      "episode_id VARCHAR NOT NULL,",
      "patient_id VARCHAR NOT NULL,",
      "index_encounter_id VARCHAR NOT NULL,",
      "admission_time TIMESTAMPTZ NOT NULL,",
      "discharge_time TIMESTAMPTZ NOT NULL,",
      "followup_window_end TIMESTAMPTZ NOT NULL,",
      "disposition VARCHAR NOT NULL CHECK (disposition IN",
      "('accepted', 'provider_failure', 'window_closed',",
      "'known_readmission', 'known_death')),",
      "probability DOUBLE, failure_kind VARCHAR, failure_reason VARCHAR,",
      "terminal_event_id VARCHAR, terminal_event_type VARCHAR,",
      "terminal_occurred_at TIMESTAMPTZ,",
      "terminal_available_at TIMESTAMPTZ,",
      "PRIMARY KEY (run_id, episode_id),",
      "FOREIGN KEY (run_id) REFERENCES runs(run_id))"
    ))
    complete <- TRUE
  }, finally = {
    if (!is.null(connection) && DBI::dbIsValid(connection)) {
      DBI::dbDisconnect(connection, shutdown = TRUE)
    }
    if (!complete && dir.exists(state)) {
      contents <- list.files(state, all.files = TRUE, no.. = TRUE)
      if (all(contents %in% c("history.duckdb", "history.duckdb.wal"))) {
        unlink(state, recursive = TRUE)
      }
    }
  })
  invisible(root)
}

# Open existing state only. In particular, a read must never create a database.
rrp_history_connect <- function(project_root, read_only = FALSE) {
  database <- file.path(project_root, "state", "history.duckdb")
  if (!file.exists(database) || dir.exists(database)) {
    stop("Project history is not initialized; call rrp_state_init() first.",
         call. = FALSE)
  }
  DBI::dbConnect(duckdb::duckdb(), dbdir = database,
                 read_only = read_only)
}

# Persist one completed run and all Stage 3.2 assessment rows in one transaction.
# An omitted run_id is generated by DuckDB; the primary key rejects reuse.
rrp_write_history <- function(project_root, run, assessments) {
  fields <- c("project_id", "as_of_time", "created_at",
              "source_mapping_script", "risk_provider_script")
  if (!is.list(run) || !all(fields %in% names(run))) {
    stop("Run metadata needs project identity, times, and script references.",
         call. = FALSE)
  }
  for (field in c("project_id", "source_mapping_script",
                  "risk_provider_script")) {
    value <- run[[field]]
    if (!is.character(value) || length(value) != 1L || is.na(value) ||
        !nzchar(trimws(value))) {
      stop(sprintf("Run %s must be one nonblank string.", field),
           call. = FALSE)
    }
  }
  for (field in c("as_of_time", "created_at")) {
    if (length(run[[field]]) != 1L) {
      stop(sprintf("Run %s must be one finite UTC POSIXct instant.", field),
           call. = FALSE)
    }
    rrp_check_utc_time(run[[field]], field)
  }
  if (!is.null(run$run_id) &&
      (!is.character(run$run_id) || length(run$run_id) != 1L ||
       is.na(run$run_id) || !nzchar(trimws(run$run_id)))) {
    stop("Run run_id must be one nonblank string.", call. = FALSE)
  }

  columns <- c("episode_id", "patient_id", "index_encounter_id",
               "admission_time", "discharge_time", "followup_window_end",
               "disposition", "probability", "failure_kind", "failure_reason",
               "terminal_event_id", "terminal_event_type",
               "terminal_occurred_at", "terminal_available_at")
  if (!is.data.frame(assessments) ||
      !all(columns %in% names(assessments))) {
    stop("Assessments must contain the Stage 3.2 result columns.",
         call. = FALSE)
  }
  assessments <- assessments[columns]
  text_columns <- c("episode_id", "patient_id", "index_encounter_id",
                    "disposition", "failure_kind", "failure_reason",
                    "terminal_event_id", "terminal_event_type")
  time_columns <- c("admission_time", "discharge_time",
                    "followup_window_end", "terminal_occurred_at",
                    "terminal_available_at")
  if (!all(vapply(assessments[text_columns], is.character, logical(1))) ||
      !is.numeric(assessments$probability) ||
      !all(vapply(assessments[time_columns], function(value) {
        inherits(value, "POSIXct") &&
          identical(attr(value, "tzone"), "UTC")
      }, logical(1)))) {
    stop("Assessments have incompatible identifier, probability, or UTC time types.",
         call. = FALSE)
  }

  connection <- rrp_history_connect(project_root)
  on.exit(DBI::dbDisconnect(connection, shutdown = TRUE), add = TRUE)
  run_id <- if (is.null(run$run_id)) {
    DBI::dbGetQuery(connection, "SELECT uuid() AS run_id")$run_id[[1L]]
  } else {
    run$run_id
  }
  run_row <- data.frame(
    run_id = run_id, project_id = run$project_id,
    as_of_time = run$as_of_time, created_at = run$created_at,
    source_mapping_script = run$source_mapping_script,
    risk_provider_script = run$risk_provider_script
  )
  assessment_rows <- data.frame(run_id = rep(run_id, nrow(assessments)),
                                assessments)
  DBI::dbWithTransaction(connection, {
    DBI::dbAppendTable(connection, "runs", run_row)
    if (nrow(assessment_rows)) {
      DBI::dbAppendTable(connection, "assessments", assessment_rows)
    }
  })
  run_id
}

# Read run context without loading either project-authored function.
rrp_read_runs <- function(project_root, run_id = NULL) {
  connection <- rrp_history_connect(project_root, read_only = TRUE)
  on.exit(DBI::dbDisconnect(connection, shutdown = TRUE), add = TRUE)
  query <- "SELECT * FROM runs"
  if (!is.null(run_id)) query <- paste(query, "WHERE run_id = ?")
  query <- paste(query, "ORDER BY created_at, run_id")
  if (is.null(run_id)) DBI::dbGetQuery(connection, query) else {
    DBI::dbGetQuery(connection, query, params = list(run_id))
  }
}

# Read assessment rows with their run context and optional exact filters.
rrp_read_assessments <- function(project_root, run_id = NULL,
                                 episode_id = NULL) {
  connection <- rrp_history_connect(project_root, read_only = TRUE)
  on.exit(DBI::dbDisconnect(connection, shutdown = TRUE), add = TRUE)
  query <- paste(
    "SELECT a.*, r.project_id, r.as_of_time, r.created_at,",
    "r.source_mapping_script, r.risk_provider_script",
    "FROM assessments a JOIN runs r ON a.run_id = r.run_id"
  )
  conditions <- character()
  params <- list()
  if (!is.null(run_id)) {
    conditions <- c(conditions, "a.run_id = ?")
    params <- c(params, list(run_id))
  }
  if (!is.null(episode_id)) {
    conditions <- c(conditions, "a.episode_id = ?")
    params <- c(params, list(episode_id))
  }
  if (length(conditions)) {
    query <- paste(query, "WHERE", paste(conditions, collapse = " AND "))
  }
  query <- paste(query, "ORDER BY r.created_at, a.run_id, a.episode_id")
  if (length(params)) DBI::dbGetQuery(connection, query, params = params) else {
    DBI::dbGetQuery(connection, query)
  }
}
